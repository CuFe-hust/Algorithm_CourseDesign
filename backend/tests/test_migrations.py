def test_static_postgresql_migration_compiles_offline(monkeypatch):
    from io import StringIO
    from pathlib import Path
    from alembic import command
    from alembic.config import Config
    from app.core.config import Settings
    settings = Settings('127.0.0.1', 5433, 'algorithm_review_test', 'test_user', 'test_password', 's' * 32)
    monkeypatch.setattr(Settings, 'load', classmethod(lambda cls: settings))
    output = StringIO()
    config = Config(str(Path(__file__).resolve().parents[1] / 'alembic.ini'), output_buffer=output)
    command.upgrade(config, 'head', sql=True)
    ddl = output.getvalue()
    assert ddl.count('CREATE TABLE ') == 35  # 34 application tables plus Alembic version
    assert 'GENERATED BY DEFAULT AS IDENTITY' in ddl
    assert 'JSONB' in ddl and 'TIMESTAMP WITH TIME ZONE' in ddl
    assert "'pg0007'" in ddl
    assert 'mysql' not in ddl.lower()
