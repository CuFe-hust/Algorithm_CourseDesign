def test_postgresql_schema_has_complete_foreign_keys_and_repeatable_upgrade(monkeypatch):
    from pathlib import Path
    from alembic import command
    from alembic.config import Config
    from sqlalchemy import inspect, text
    from app.db.base import Base
    from app.db import models
    from app.db.session import make_engine
    monkeypatch.setenv('DB_NAME', 'algorithm_review_test')
    engine = make_engine()
    required = {'users', 'classes', 'student_profiles', 'courses', 'course_members', 'problems',
                'problem_versions', 'knowledge_points', 'problem_version_tags', 'assignments',
                'assignment_items', 'assignment_participants', 'submissions', 'test_suites',
                'test_cases', 'reference_solutions', 'rubrics', 'rubric_items', 'analysis_jobs',
                'judge_results', 'auth_sessions', 'request_rate_limits', 'judge_attempts',
                'judge_retry_requests','analysis_batches','analysis_input_snapshots','analysis_runs','analysis_artifacts','review_rounds','review_tasks','review_evaluations','review_analyses','review_decisions','review_commands'}
    try:
        config = Config(str(Path(__file__).resolve().parents[1] / 'alembic.ini'))
        assert engine.url.database == 'algorithm_review_test'
        assert engine.dialect.name == 'postgresql'
        assert set(inspect(engine).get_table_names()) <= required | {'alembic_version'}
        Base.metadata.drop_all(engine)
        with engine.begin() as connection:
            connection.execute(text('DROP TABLE IF EXISTS alembic_version'))
        command.upgrade(config, 'head')
        command.downgrade(config, 'base')
        assert set(inspect(engine).get_table_names()) == {'alembic_version'}
        command.upgrade(config, 'head')
        command.upgrade(config, 'head')
        assert required <= set(inspect(engine).get_table_names())
        assert len(inspect(engine).get_foreign_keys('assignment_items')) == 4
        assert engine.dialect.name == 'postgresql'
        with engine.connect() as connection:
            assert connection.scalar(text('SELECT version_num FROM alembic_version')) == 'pg0007'
            from alembic.autogenerate import compare_metadata
            from alembic.migration import MigrationContext
            assert compare_metadata(MigrationContext.configure(connection), Base.metadata) == []
        assert all(column['type'].timezone for column in inspect(engine).get_columns('auth_sessions')
                   if column['name'] in {'expires_at', 'created_at', 'last_active_at', 'absolute_expires_at'})
    finally:
        engine.dispose()


def test_postgresql_url_defaults_and_special_character_credentials(monkeypatch):
    from app.core import config
    monkeypatch.setattr(config, 'load_dotenv', lambda *args, **kwargs: None)
    for key in ('DB_HOST', 'DB_PORT', 'DB_NAME'):
        monkeypatch.delenv(key, raising=False)
    monkeypatch.setenv('DB_USER', 'test_user')
    monkeypatch.setenv('DB_PASSWORD', 'p@ss:/?#word')
    monkeypatch.setenv('APP_SECRET', 'x' * 32)
    url = config.Settings.load().url()
    assert url.drivername == 'postgresql+psycopg'
    assert url.port == 5433
    assert url.password == 'p@ss:/?#word'
    assert not url.query


def test_all_models_compile_to_postgresql_ddl():
    from sqlalchemy.dialects import postgresql
    from sqlalchemy.schema import CreateTable
    from app.db.base import Base
    from app.db import models
    assert len(Base.metadata.tables) == 34
    ddl = '\n'.join(str(CreateTable(table).compile(dialect=postgresql.dialect()))
                    for table in Base.metadata.sorted_tables)
    assert 'TIMESTAMP WITH TIME ZONE' in ddl
    assert 'JSONB' in ddl
    assert 'utf8mb4' not in ddl
    assert 'NOT is_mock' in ddl
    for table in Base.metadata.tables.values():
        for column in table.columns:
            if column.name.endswith('_at') or column.name.endswith('_deadline'):
                assert column.type.timezone, (table.name, column.name)


